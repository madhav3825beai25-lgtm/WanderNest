import "dotenv/config";
import { MongoClient } from "mongodb";
import destinations from "../src/data/destinations.js";
import packages from "../src/data/packages.js";
import hotels from "../src/data/hotels.js";

const uri = process.env.MONGODB_URI;
if (!uri) {
  console.error("Missing MONGODB_URI. Set it in your local environment before seeding.");
  process.exit(1);
}

function priceToNumber(value) {
  if (typeof value === "number") return value;
  const amount = Number(String(value ?? "").replace(/[^0-9.]/g, ""));
  return Number.isFinite(amount) ? amount : 0;
}

const dbName = process.env.MONGODB_DB_NAME || "wandernest";
const client = new MongoClient(uri, { maxPoolSize: 3, serverSelectionTimeoutMS: 8000, appName: "WanderNestSeeder" });

async function upsertMany(collection, docs) {
  if (!docs.length) return;
  await collection.bulkWrite(docs.map((document) => ({
    updateOne: {
      filter: { id: document.id, seedSource: "wandernest-sample" },
      update: { $set: document },
      upsert: true,
    },
  })), { ordered: false });

  // Remove obsolete records previously generated by this seed script only.
  const ids = docs.map((document) => document.id);
  await collection.deleteMany({ seedSource: "wandernest-sample", id: { $nin: ids } });
}

try {
  await client.connect();
  const db = client.db(dbName);

  const destinationDocs = destinations.map((item) => ({
    ...item,
    priceInr: priceToNumber(item.price),
    seedSource: "wandernest-sample",
    updatedAt: new Date(),
  }));

  const packageDocs = packages.map((item) => {
    const match = destinations.find((destination) =>
      String(item.location || "").toLowerCase().includes(String(destination.name).toLowerCase())
    );
    return {
      ...item,
      priceInr: priceToNumber(item.price),
      destinationId: match?.id ?? null,
      seedSource: "wandernest-sample",
      updatedAt: new Date(),
    };
  });

  const hotelDocs = hotels.map((item) => ({
    ...item,
    priceInr: priceToNumber(item.price),
    seedSource: "wandernest-sample",
    updatedAt: new Date(),
  }));

  await upsertMany(db.collection("destinations"), destinationDocs);
  await upsertMany(db.collection("packages"), packageDocs);
  await upsertMany(db.collection("hotels"), hotelDocs);

  await db.collection("hotels").createIndex({ destinationId: 1, price: 1 });
  await db.collection("hotels").createIndex({ name: 1 });
  await db.collection("bookings").createIndex({ userId: 1, createdAt: -1 });
  await db.collection("bookings").createIndex({ reference: 1 }, { unique: true });

  console.log(`Seed complete: ${destinationDocs.length} destinations, ${hotelDocs.length} sample hotels, ${packageDocs.length} packages.`);
  console.log(`Database: ${dbName}. Existing non-seed documents are retained.`);
} catch (error) {
  console.error("MongoDB seed failed:", error.message);
  process.exitCode = 1;
} finally {
  await client.close();
}
